"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const source = fs.readFileSync(require("node:path").join(__dirname, "../public/admin.js"), "utf8");
const start = source.indexOf("function getOfferWarnings(");
const end = source.indexOf("function displayWarning(", start);
assert(start >= 0 && end > start, "QA helpers must exist");
const context = vm.createContext({ AYAHotelOccupancy: require("../public/hotel-occupancy") });
vm.runInContext(source.slice(start, end) + "\nthis.getOfferWarnings = getOfferWarnings;", context);
const warnings = (offer) => Array.from(context.getOfferWarnings(offer));
const base = { guests: "2 възрастни", travelDates: "12-19 Oct 2026", hotels: [{ occupancy: { adults: 2, children: 0, rooms: 1, confirmed: true }, selected: true, meal: "Закуска", images: ["https://hotel.example/photo.jpg"] }] };
assert.equal(warnings(base).length, 0);
assert(warnings({ ...base, guests: "" }).some(x => x.includes("пътуващи")));
assert(warnings({ ...base, travelDates: "" }).some(x => x.includes("дати")));
assert(warnings({ ...base, hotels: [{ ...base.hotels[0], meal: "" }] }).some(x => x.includes("изхранването")));
assert(warnings({ ...base, hotels: [{ ...base.hotels[0], images: [] }] }).some(x => x.includes("снимки")));
assert.equal(warnings({ ...base, validationWarnings: ["[INFO] Airport DOH"] }).length, 1);
assert(warnings({ ...base, hotels: [{ ...base.hotels[0], description: "За 2 възрастни и 2 деца" }] }).some(x => x.includes("деца")));
assert(!warnings({ ...base, guests: "2 възрастни и 2 деца", hotels: [{ ...base.hotels[0], occupancy: { adults: 2, children: 2, rooms: 1, confirmed: true }, description: "За 2 възрастни и 2 деца" }] }).some(x => x.includes("деца")));
assert(warnings({ ...base, hotels: [base.hotels[0], { meal: "", images: [] }] }).some(x => x.includes("изхранването")));
console.log("AYA-07 missing-data warning regression: PASS");
